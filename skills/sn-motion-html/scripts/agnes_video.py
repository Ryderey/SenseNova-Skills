#!/usr/bin/env python3
"""Generate this project's video clips: SenseNova images, animated by Agnes video.

The script is the executor, not the author. It reads the clip prompts and anchor
settings that a host Agent already wrote into prompts/video-manifest.json, asks
the project's own SenseNova image skill for each anchor image, hands that image's
public URL to the video model, normalizes the downloaded clip with FFmpeg, and
writes it into assets/video/dives/.

Image work belongs to SenseNova; the video provider only animates what it is
given. It accepts no local media, so every frame or reference must be a public
HTTPS URL. One anchor mode per intent covers that:

  generate   the anchor image is generated by SenseNova and its URL response is
             handed to the video call (the default for a dive; no host needed)
  reference  public images that guide the clip; a connector borrows the anchor
             URLs recorded for the chapters on either side of its seam
  url        the record's first_frame / last_frame URLs, published by the user

Every clip must explicitly select an image anchor mode; text-only video is not
part of this image-led workflow.

Use --dry-run to print every call it would make without spending anything.
"""

