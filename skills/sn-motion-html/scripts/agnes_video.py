def run_agnes(cli: Path, args: list[str], output_dir: Path) -> dict:
    """Run one Agnes subcommand and return its JSON object."""
    if not args or args[0] != "video-generate":
        raise PipelineError("Agnes is video-only; image operations must use SenseNova")
    env = dict(os.environ, AGNES_OUTPUT_DIR=str(output_dir))
    if not env.get("AGNES_API_KEY", "").strip():
        raise PipelineError("AGNES_API_KEY is not set in the environment")
    result = subprocess.run(
        [sys.executable, str(cli), *args],
        capture_output=True, text=True, encoding="utf-8", env=env, timeout=1800,
    )
    lines = [line for line in result.stdout.splitlines() if line.strip()]
    if result.returncode != 0 or not lines:
        detail = (result.stderr or result.stdout or "").strip()[-800:]
        raise PipelineError(f"agnes {' '.join(args[:1])} failed (exit {result.returncode}): {detail}")
    try:
        return json.loads(lines[-1])
    except json.JSONDecodeError as exc:
        raise PipelineError(f"agnes did not return JSON: {exc}") from exc


def sense_nova_generate(
    image_runner: Path, *, prompt_path: Path, size: str, ratio: str, save_path: Path,
) -> str:
    """Generate one anchor image with the project's SenseNova runtime.

    Returns the provider's public URL for it: the video model accepts no local
    media, and a URL response is how the image side hands one over.
    """
    result = subprocess.run(
        [sys.executable, str(image_runner), "sn-image-generate",
         "--model", IMAGE_MODEL, "--no-fallback", "--no-watermark", "--image-format", "png",
         "--prompt-path", str(prompt_path), "--image-size", size, "--aspect-ratio", ratio,
         "--response-format", "url", "--save-path", str(save_path), "--output-format", "json"],
        capture_output=True, text=True, encoding="utf-8", timeout=900,
        env=dict(os.environ, SN_IMAGE_GEN_MODEL_TYPE="sensenova"),
    )
    lines = [line for line in (result.stdout or "").splitlines() if line.strip()]
    if result.returncode != 0 or not lines:
        detail = (result.stderr or result.stdout or "").strip()[-600:]
        raise PipelineError(f"image generation failed (exit {result.returncode}): {detail}")
    try:
        payload = json.loads(lines[-1])
    except json.JSONDecodeError as exc:
        raise PipelineError(f"image generation did not return JSON: {exc}") from exc
    if (payload.get("status") != "ok" or payload.get("model") != IMAGE_MODEL
            or payload.get("fallback_used")):
        raise PipelineError("anchor generation must succeed with the selected SenseNova model without fallback")
    url = str(payload.get("provider_url") or "")
    if not public_https(url):
        raise PipelineError(
            "the image endpoint returned no public URL for the anchor "
            f"(model {payload.get('model')!r}); the video model cannot take a local file"
        )
    return url


def read_prompt(root: Path, relative: str, label: str) -> str:
    path = manifest_path(root, relative, label, root / "prompts", must_exist=True)
    text = path.read_text(encoding="utf-8").strip()
    if not text:
        raise PipelineError(f"{label} prompt is empty: {path}")
    return text


def manifest_path(
    root: Path, raw: str, label: str, allowed_dir: Path, *, must_exist: bool = False
) -> Path:
    """Resolve a manifest path without allowing absolute or symlink escapes."""
    if not isinstance(raw, str) or not raw.strip():
        raise PipelineError(f"{label} path must be a non-empty project-relative path")
    candidate = Path(raw)
    if candidate.is_absolute() or candidate.drive or raw.startswith(("\\\\", "//")):
        raise PipelineError(f"{label} path must be project-relative: {raw}")
    root = root.resolve()
    allowed = allowed_dir.resolve()
    try:
        resolved = (root / candidate).resolve()
        resolved.relative_to(allowed)
    except (ValueError, OSError) as exc:
        raise PipelineError(f"{label} path escapes {allowed.relative_to(root)}: {raw}") from exc
    if must_exist and not resolved.is_file():
        raise PipelineError(f"{label} prompt is missing: {resolved}")
    return resolved


def probe_video(path: Path) -> dict:
    if shutil.which("ffprobe") is None:
        raise PipelineError("ffprobe is required to verify normalized provider clips")
    result = subprocess.run(
        [
            "ffprobe", "-v", "error", "-select_streams", "v:0",
            "-show_entries", "stream=codec_name,width,height,avg_frame_rate,duration",
            "-show_entries", "format=duration", "-of", "json", str(path),
        ],
        capture_output=True, text=True, encoding="utf-8",
    )
    if result.returncode != 0:
        raise PipelineError(f"cannot inspect video {path.name}: {result.stderr.strip()[-400:]}")
    try:
        return json.loads(result.stdout)
    except json.JSONDecodeError as exc:
        raise PipelineError(f"ffprobe returned invalid JSON for {path.name}") from exc


def validate_normalized(path: Path, *, seconds: int, width: int, height: int, fps: int) -> None:
    data = probe_video(path)
    streams = data.get("streams") or []
    if not streams:
        raise PipelineError(f"normalized clip has no video stream: {path.name}")
    stream = streams[0]
    try:
        numerator, denominator = str(stream.get("avg_frame_rate", "0/1")).split("/", 1)
        actual_fps = float(numerator) / float(denominator)
        duration = float(stream.get("duration") or (data.get("format") or {}).get("duration") or 0)
    except (ValueError, ZeroDivisionError, TypeError) as exc:
        raise PipelineError(f"normalized clip has invalid media metadata: {path.name}") from exc
    if stream.get("codec_name") != "h264" or stream.get("width") != width or stream.get("height") != height:
        raise PipelineError(f"normalized clip has wrong codec or dimensions: {path.name}")
    if abs(actual_fps - fps) > 0.01:
        raise PipelineError(f"normalized clip has wrong frame rate: {path.name}")
    if duration < seconds - (1 / fps) or duration > seconds + 0.15:
        raise PipelineError(f"normalized clip has wrong duration {duration:.3f}s: {path.name}")


def valid_normalized(path: Path, *, seconds: int, width: int, height: int, fps: int) -> bool:
    if not path.is_file() or path.stat().st_size == 0:
        return False
    try:
        validate_normalized(path, seconds=seconds, width=width, height=height, fps=fps)
    except (PipelineError, OSError):
        return False
    return True


def normalize(source: Path, target: Path, *, seconds: int, width: int, height: int, fps: int,
              crf: int) -> None:
    """Normalize a provider clip to the manifest's exact target."""
    if shutil.which("ffmpeg") is None:
        raise PipelineError("ffmpeg is required to normalize provider clips")
    target.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(prefix=f".{target.stem}.", suffix=target.suffix, dir=target.parent)
    os.close(handle)
    filter_graph = (
        f"scale={width}:{height}:force_original_aspect_ratio=increase,"
        f"crop={width}:{height},fps={fps},"
        f"tpad=stop_mode=clone:stop_duration={seconds},trim=duration={seconds},"
        "setpts=PTS-STARTPTS"
    )
    try:
        subprocess.run(
            ["ffmpeg", "-v", "error", "-y", "-i", str(source),
             "-vf", filter_graph, "-c:v", "libx264", "-profile:v", "high", "-crf", str(crf),
             "-pix_fmt", "yuv420p", "-g", "8", "-an", "-movflags", "+faststart", temporary],
            check=True,
        )
        validate_normalized(Path(temporary), seconds=seconds, width=width, height=height, fps=fps)
        os.replace(temporary, target)
    finally:
        Path(temporary).unlink(missing_ok=True)


def write_still(clip: Path, target: Path, *, force: bool) -> None:
    """Use the clip's own first frame as the page still, so page and clip match."""
    from PIL import Image

    if target.exists() and not force:
        raise PipelineError(f"refusing to overwrite an existing still: {target.name} (pass --force)")
    target.parent.mkdir(parents=True, exist_ok=True)
    frame_handle, frame_name = tempfile.mkstemp(prefix=f".{target.stem}.", suffix=".frame.png", dir=target.parent)
    os.close(frame_handle)
    frame = Path(frame_name)
    handle, temporary = tempfile.mkstemp(prefix=f".{target.stem}.", suffix=".webp", dir=target.parent)
    os.close(handle)
    try:
        subprocess.run(
            ["ffmpeg", "-v", "error", "-y", "-i", str(clip), "-frames:v", "1", str(frame)],
            check=True,
        )
        with Image.open(frame) as image:
            image.convert("RGB").save(temporary, "WEBP", quality=90, method=6)
        os.replace(temporary, target)
    finally:
        frame.unlink(missing_ok=True)
        Path(temporary).unlink(missing_ok=True)


def resolve_references(root: Path, record: dict) -> list[str]:
    """Return this clip's reference-image URLs, reading recorded anchors at run time.

    A connector without an explicit list borrows the anchor images of the two
    chapters it joins. They are read here rather than at plan time so one
    invocation can generate the dives first and then their connectors.
    """
    if record["references"]:
        return list(record["references"])
    if not record["references_from"]:
        return []
    state = load_state(root)
    resolved: list[str] = []
    missing: list[str] = []
    expired: list[str] = []
    for clip_id in record["references_from"]:
        entry = state["clips"].get(clip_id) or {}
        url = str(entry.get("anchor_url") or "")
        age = anchor_age_hours(entry)
        if not public_https(url):
            missing.append(clip_id)
        elif age is not None and age > ANCHOR_MAX_AGE_HOURS:
            expired.append(f"{clip_id} ({age:.1f}h)")
        else:
            resolved.append(url)
    if missing:
        raise PipelineError(
            f"{record['id']}: no anchor image is recorded for {', '.join(missing)} in "
            f"{STATE_RELATIVE}; generate those dives first, or list reference_images explicitly"
        )
    if expired:
        # A provider URL is pre-signed, so an old one is refused rather than sent
        # and rejected by the video model mid-run.
        raise PipelineError(
            f"{record['id']}: the recorded anchor URL has expired for {', '.join(expired)}; "
            "re-run those dives with --force to refresh them, or list reference_images explicitly"
        )
    return resolved


def plan_records(root: Path, manifest: dict) -> list[dict]:
    """Build one execution plan per clip, with every problem reported up front.

    Dives carry the chapter's motion and feed the page still. Connectors join two
    chapters: their boundary frames are local extracts, so they are anchored
    through provider-hosted images instead — `reference` uses the two chapters'
    anchor images (both already public), and `url` uses frames the user hosts.
    """
    model = str(manifest.get("model") or "")
    if model not in MODELS:
        raise PipelineError(
            f"prompts/video-manifest.json must set a known video model "
            f"({', '.join(MODELS)}); got {model!r}"
        )
    spec = MODELS[model]
    seconds = manifest.get("duration")
    if isinstance(seconds, bool) or not isinstance(seconds, (int, float)) or seconds <= 0:
        raise PipelineError(f"duration must be a positive number of seconds; got {seconds!r}")
    durations = spec["whole_second_durations"]
    if durations is not None and (not float(seconds).is_integer() or int(seconds) not in durations):
        first, last = durations[0], durations[-1]
        raise PipelineError(f"{spec['label']} needs whole-second durations from {first} to {last}; got {seconds!r}")
    if durations is None:
        # v2.0 aligns to 8n+1 frames and clamps at 441, so a request beyond that
        # budget would silently come back shorter than asked.
        fps = int(manifest.get("fps", 24))
        requested = round(float(seconds) * fps)
        if frame_count(float(seconds), fps) < 9:
            raise PipelineError(f"{spec['label']} needs a longer clip than {seconds!r}s")
        if requested > 441:
            raise PipelineError(
                f"{spec['label']} renders at most 441 frames ({441 / fps:.1f}s at {fps}fps); "
                f"{seconds!r}s would be clamped, so it is refused instead"
            )
    resolution = str(manifest.get("resolution") or "")
    if spec["resolution_fixed"]:
        if resolution.strip().lower() != spec["resolution_fixed"].lower():
            raise PipelineError(
                f"{spec['label']} requires resolution {spec['resolution_fixed']}; got {resolution!r}"
            )
    elif not resolution.strip():
        raise PipelineError(f"{spec['label']} requires an explicit resolution such as 1080p")

    records: list[dict] = []
    groups = (
        ("dive", "dives", "assets/video/dives", True),
        ("connector", "connectors", "assets/video/connectors", False),
    )
    for kind, key, default_dir, has_still in groups:
        for entry in manifest.get(key) or []:
            if not isinstance(entry, dict):
                raise PipelineError(f"every {key}[] entry must be an object")
            clip_id = str(entry.get("id") or "")
            if not SAFE_ID.match(clip_id):
                raise PipelineError(f"{key}[].id must be filename-safe; got {clip_id!r}")
            anchor = str(entry.get("anchor_mode") or "")
            if anchor not in ANCHOR_MODES:
                raise PipelineError(f"{clip_id}.anchor_mode must be one of {ANCHOR_MODES}; got {anchor!r}")

            first_frame = str(entry.get("first_frame") or "").strip()
            last_frame = str(entry.get("last_frame") or "").strip()
            references = [str(value).strip() for value in entry.get("reference_images") or []]
            references_from: list[str] = []
            anchor_prompt = None

            if anchor == "generate":
                if kind == "connector":
                    raise PipelineError(
                        f"{clip_id}: a connector joins two existing chapters, so a generated anchor would not "
                        "be either boundary. Use reference or url instead"
                    )
                anchor_prompt = read_prompt(root, str(entry.get("anchor_prompt") or ""), f"{clip_id} anchor")
            elif anchor == "url":
                frames = [value for value in (first_frame, last_frame) if value]
                if not frames:
                    raise PipelineError(f"{clip_id}.anchor_mode is 'url' but neither first_frame nor last_frame is set")
                for value in frames:
                    if not public_https(value):
                        raise PipelineError(f"{clip_id}: a hosted frame must be a public HTTPS URL; got {value!r}")
            elif anchor == "reference":
                if not references:
                    # Borrow the two chapters' own anchor images. They are resolved
                    # when this clip runs, not when the plan is built, so a single
                    # invocation can generate the dives and then their connectors.
                    if kind != "connector":
                        raise PipelineError(
                            f"{clip_id}.anchor_mode is 'reference' but no reference_images are listed"
                        )
                    neighbours = [str(entry.get("from") or ""), str(entry.get("to") or "")]
                    if not all(neighbours):
                        raise PipelineError(
                            f"{clip_id}: a reference connector needs both 'from' and 'to', or an explicit "
                            "reference_images list"
                        )
                    references_from = neighbours
                if len(references) > spec["boundary_images"]:
                    raise PipelineError(
                        f"{clip_id} lists {len(references)} reference images; {spec['label']} accepts at most "
                        f"{spec['boundary_images']}"
                    )
                for value in references:
                    if not public_https(value):
                        raise PipelineError(f"{clip_id}: a reference image must be a public HTTPS URL; got {value!r}")

            records.append({
                "kind": kind,
                "id": clip_id,
                "anchor_mode": anchor,
                "first_frame": first_frame,
                "last_frame": last_frame,
                "references": references,
                "references_from": references_from,
                "anchor_prompt": anchor_prompt,
                "anchor_prompt_path": str(entry.get("anchor_prompt") or ""),
                "prompt": read_prompt(root, str(entry.get("prompt") or ""), f"{clip_id} motion"),
                "output": str(entry.get("output") or f"{default_dir}/{clip_id}.mp4"),
                "output_path": manifest_path(
                    root,
                    str(entry.get("output") or f"{default_dir}/{clip_id}.mp4"),
                    f"{clip_id} output",
                    root / "assets" / "video",
                ),
                "still": f"assets/images/scenes/{clip_id}.webp" if has_still else None,
            })
    if not records:
        raise PipelineError("prompts/video-manifest.json declares no clips")
    return records


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("project_root", type=Path)
    parser.add_argument("--agnes-cli", help="absolute path to agnes_media.py (video only)")
    parser.add_argument("--image-cli",
                        help="absolute path to the SenseNova runner, sn-image-base/scripts/sn_agent_runner.py")
    parser.add_argument("--only", action="append", default=[], metavar="ID",
                        help="limit the run to these dive ids (repeatable)")
    parser.add_argument("--seed", type=int, help="seed for every clip in this run")
    parser.add_argument("--write-stills", action="store_true",
                        help="write each clip's first frame as the page still")
    parser.add_argument("--force", action="store_true", help="overwrite existing clips")
    parser.add_argument("--dry-run", action="store_true",
                        help="print the plan and every call without spending anything")
    args = parser.parse_args()

    root = args.project_root.expanduser().resolve()
    try:
        story = load_story(root)
        mode = resolve_media_mode(story)
        problems = validate_story(root, story, mode)
        if problems:
            raise PipelineError("story problems: " + "; ".join(problems))
        manifest_path = root / "prompts" / "video-manifest.json"
        if not manifest_path.is_file():
            raise PipelineError(f"video mode needs a manifest: {manifest_path}")
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        records = plan_records(root, manifest)
    except (ProjectError, PipelineError, json.JSONDecodeError) as exc:
        print(f"FAIL {exc}")
        return 1

    wanted = set(args.only)
    if wanted:
        unknown = wanted - {record["id"] for record in records}
        if unknown:
            print(f"FAIL --only names unknown dive ids: {', '.join(sorted(unknown))}")
            return 1
        records = [record for record in records if record["id"] in wanted]

    cli = generator = None
    if not args.dry_run:
        try:
            load_project_env(root)
            cli = agnes_cli(args.agnes_cli)
            if not os.environ.get("AGNES_API_KEY", "").strip():
                raise PipelineError("AGNES_API_KEY is not set; configure the process environment or project .env")
            if any(record["anchor_mode"] == "generate" for record in records):
                generator = image_cli(args.image_cli)
        except (PipelineError, OSError) as exc:
            print(f"FAIL {exc}")
            return 1

    try:
        width = int(manifest.get("target_width", 1280))
        height = int(manifest.get("target_height", 720))
        fps = int(manifest.get("fps", 24))
        seconds = int(manifest["duration"])
    except (KeyError, TypeError, ValueError) as exc:
        print(f"FAIL target dimensions, fps, and duration must be integers: {exc}")
        return 1
    ratio = str(manifest.get("ratio", "16:9"))
    model = str(manifest.get("model") or "")
    resolution = str(manifest.get("resolution") or "")
    crf = manifest.get("crf", 23)
    if width < 1 or height < 1 or fps < 1:
        print(f"FAIL target dimensions and fps must be positive: {width}x{height}@{fps}fps")
        return 1
    anchor_image_size = str(manifest.get("anchor_image_size", "2k"))
    if anchor_image_size.lower() not in {"1k", "2k", "4k"}:
        print(f"FAIL anchor_image_size must be 1k, 2k or 4k; got {anchor_image_size!r}")
        return 1
    if isinstance(crf, bool) or not isinstance(crf, int) or not 0 <= crf <= 51:
        print(f"FAIL crf must be an integer from 0 to 51 (lower is better quality and larger); got {crf!r}")
        return 1
    ratio_parts = ratio.split(":")
    if len(ratio_parts) != 2 or any(not part.isdigit() or int(part) < 1 for part in ratio_parts):
        print(f"FAIL ratio must be two positive integers like 16:9; got {ratio!r}")
        return 1
    if shutil.which("ffmpeg") is None or shutil.which("ffprobe") is None:
        print("FAIL ffmpeg and ffprobe are required before generating video")
        return 1
    if args.write_stills:
        try:
            import PIL  # noqa: F401
        except ImportError:
            print("FAIL Pillow is required before writing video stills")
            return 1
    # One directory per run: provider downloads and generated anchors are
    # intermediates, so the run removes them on the way out rather than letting
    # them accumulate across projects.
    workdir = None
    if not args.dry_run:
        workdir = Path(tempfile.mkdtemp(prefix="sn-motion-video-"))
        atexit.register(shutil.rmtree, workdir, ignore_errors=True)

    print(f"Model: {model} ({MODELS[model]['label']})  {seconds}s  {ratio}  "
          f"{width}x{height}@{fps}fps  provider resolution "
          f"{MODELS[model]['resolution_fixed'] or resolution}  crf {crf}")
    print(f"Clips: {len(records)}")
    failures: list[str] = []
    for record in records:
        output = record["output_path"]
        anchor = record["anchor_mode"]
        print(f"\n== {record['kind']} {record['id']}  anchor={anchor}")
        if output.is_file() and not args.force:
            if valid_normalized(output, seconds=seconds, width=width, height=height, fps=fps):
                if not args.dry_run:
                    if record["kind"] == "dive" and anchor == "url":
                        if public_https(record["first_frame"]):
                            record_anchor(root, record["id"], record["first_frame"], anchor, model=None)
                        else:
                            clear_anchor(root, record["id"])
                    elif record["kind"] == "dive" and anchor != "generate":
                        clear_anchor(root, record["id"])
                if args.write_stills and record["still"]:
                    still = root / record["still"]
                    if not still.is_file():
                        if args.dry_run:
                            print(f"   would write missing still {record['still']}")
                            continue
                        try:
                            write_still(output, still, force=False)
                            print(f"   wrote missing still {record['still']}")
                        except (PipelineError, subprocess.CalledProcessError, OSError) as exc:
                            failures.append(f"{record['id']}: {exc}")
                            print(f"   FAIL {exc}")
                    else:
                        print(f"   skip: {record['output']} and still already exist")
                else:
                    print(f"   skip: {record['output']} already exists (pass --force to replace)")
                continue
            print(f"   existing clip is invalid; regenerating {record['output']}")
        if args.dry_run:
            if anchor == "generate":
                first_line = record["anchor_prompt"].splitlines()[0]
                print(f"   would call sn-image-generate ({IMAGE_MODEL}, {anchor_image_size}, {ratio}, "
                      f"response-format url): {first_line}...")
            elif anchor == "url":
                if record["first_frame"]:
                    print(f"   would use first_frame {record['first_frame']}")
                if record["last_frame"]:
                    print(f"   would use last_frame {record['last_frame']}")
            elif anchor == "reference":
                if record["references"]:
                    resolved = list(record["references"])
                else:
                    # Resolved at run time; a dry run reports either the real URLs or
                    # clearly-marked placeholders, so it can still show the call shape.
                    try:
                        resolved = resolve_references(root, record)
                    except PipelineError as exc:
                        print(f"   note: {exc}")
                        resolved = [f"<anchor-url-of-{name}>" for name in record["references_from"]]
                for url in resolved:
                    print(f"   would use boundary image {url}")
                record["references"] = resolved
            # Show exactly which provider call this clip becomes on this model. A
            # generated anchor does not exist yet, so its URL is a placeholder here.
            record["run_first_frame"] = (
                "<anchor-url-created-by-image-generate>" if anchor == "generate" else record["first_frame"]
            )
            record["run_last_frame"] = record["last_frame"]
            if anchor == "reference":
                try:
                    record["references"] = resolve_references(root, record)
                except PipelineError:
                    record["references"] = []
            try:
                planned = video_args(model, record, seconds=seconds, ratio=ratio,
                                     resolution=resolution, fps=fps)
            except PipelineError as exc:
                # An unsupported combination is a planning result, not a crash: the
                # dry run reports it and keeps checking the remaining clips.
                print(f"   would fail: {exc}")
                failures.append(f"{record['id']}: {exc}")
                continue
            media_flags = [value for value in planned if value != record["prompt"]]
            print(f"   would call video-generate {' '.join(media_flags)}")
            print(f"   prompt: {record['prompt'].splitlines()[0]}...")
            print(f"   would normalize into {record['output']}")
            if anchor == "generate":
                print("   would record the anchor url in .motion-state/video-anchors.json")
            # Only a dive carries a page still; a connector has no still of its own.
            if args.write_stills and record["still"]:
                print(f"   would write still {record['still']}")
            continue
        try:
            if record["kind"] == "dive":
                clear_anchor(root, record["id"])
            first_frame = record["first_frame"]
            if anchor == "generate":
                first_frame = sense_nova_generate(
                    generator,
                    prompt_path=root / record["anchor_prompt_path"],
                    size=anchor_image_size, ratio=ratio,
                    save_path=workdir / f"anchor-{record['id']}.png",
                )
                print(f"   anchor image (SenseNova): {first_frame}")

            # One place decides which media this clip sends; video_args() then
            # translates that intent into the selected model's own arguments.
            record["run_first_frame"] = "" if anchor == "reference" else first_frame
            record["run_last_frame"] = record["last_frame"] if anchor != "reference" else ""
            if anchor == "reference":
                record["references"] = resolve_references(root, record)
            provider_args = [
                "video-generate",
                *video_args(model, record, seconds=seconds, ratio=ratio,
                            resolution=resolution, fps=fps),
                "--timeout-seconds", "900", "--poll-interval-seconds", "10",
                "--prompt", record["prompt"],
            ]
            if args.seed is not None:
                provider_args += ["--seed", str(args.seed)]

            video = run_agnes(cli, provider_args, workdir)
            downloaded = str(video.get("local_path") or "")
            if not downloaded or not Path(downloaded).is_file():
                raise PipelineError(f"{record['id']}: provider returned no downloaded clip")
            print(f"   provider clip: {Path(downloaded).name}")

            normalize(Path(downloaded), output, seconds=seconds, width=width, height=height, fps=fps,
                      crf=crf)
            print(f"   wrote {record['output']}")
            if record["kind"] == "dive" and anchor in {"generate", "url"} and public_https(first_frame):
                # Remember which image the clip starts from, so a later connector can
                # reference the frame the page actually shows.
                record_anchor(root, record["id"], first_frame, anchor,
                              model=IMAGE_MODEL if anchor == "generate" else None)
                print("   recorded anchor url in .motion-state/video-anchors.json")
            # Only a dive carries a page still; a connector has no still of its own.
            if args.write_stills and record["still"]:
                write_still(output, root / record["still"], force=args.force)
                print(f"   wrote {record['still']}")
        except (PipelineError, subprocess.CalledProcessError, OSError) as exc:
            failures.append(f"{record['id']}: {exc}")
            print(f"   FAIL {exc}")

    if failures:
        print("\nFailures:")
        for failure in failures:
            print(f"- {failure}")
        return 1
    if args.dry_run:
        print("\nDry run complete: nothing was generated.")
    else:
        print("\nAll requested clips are in place. Run scripts/verify_media.py next.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
