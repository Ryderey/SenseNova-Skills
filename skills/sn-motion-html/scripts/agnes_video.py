AGNES_MODEL = "agnes-video-2.5-flash"
IMAGE_MODEL = "sensenova-u1.5-lite"  # anchors come from the project's SenseNova skill
# A SenseNova image URL is pre-signed and expires; refresh the anchors by
# re-running the dives before that window closes if a connector is generated later.
ANCHOR_MAX_AGE_HOURS = 20
ANCHOR_MODES = ("generate", "url", "reference")
SAFE_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
# Private run state: the provider URL of every generated anchor, so a later
# connector can reference the frames the page actually shows. Never served and
# never a deliverable.
STATE_RELATIVE = ".motion-state/video-anchors.json"

# The two video models express the same intent with different arguments. Flash is
# capped at 720P and takes named frames; v2.0 renders higher resolutions but takes
# a single image (ti2vid) or a first/last pair (keyframes).
MODELS: dict[str, dict] = {
    "agnes-video-2.5-flash": {
        "label": "Agnes Video 2.5 Flash",
        "resolution_fixed": "720P",
        "whole_second_durations": range(4, 13),
        "named_frames": True,
        "boundary_images": 5,
        "frame_rate_option": False,
    },
    "agnes-video-v2.0": {
        "label": "Agnes Video v2.0",
        "resolution_fixed": None,
        "whole_second_durations": None,   # frame-aligned instead, see frame_count()
        "named_frames": False,
        "boundary_images": 2,             # a keyframes transition takes two boundaries
        "frame_rate_option": True,
    },
}
DEFAULT_MODEL = "agnes-video-v2.0"


class PipelineError(RuntimeError):
    """A problem that must stop the run before any provider call."""


def public_https(value: str) -> bool:
    """Both models accept only public HTTPS media inputs."""
    return value.strip().lower().startswith("https://")


def frame_count(seconds: float, fps: int) -> int:
    """v2.0 renders 8n+1 frames, capped at 441 (about 18s at 24fps)."""
    raw = max(1, min(round(seconds * fps), 441))
    return min(max(1, 8 * round((raw - 1) / 8.0) + 1), 441)


def video_args(
    model: str, record: dict, *, seconds: float, ratio: str, resolution: str, fps: int,
) -> list[str]:
    """Build the provider arguments for one clip on the selected model.

    The clip's intent is the same either way — start from an anchor or cross between
    two boundaries — but the two models name it
    differently, so the mapping lives here rather than in the manifest.
    """
    spec = MODELS[model]
    args: list[str] = ["--model", model, "--duration", str(seconds), "--resolution",
                       spec["resolution_fixed"] or resolution, "--aspect-ratio", ratio]
    if spec["frame_rate_option"]:
        args += ["--frame-rate", str(fps)]
    anchor = record["anchor_mode"]
    first, last = record["run_first_frame"], record["run_last_frame"]

    if anchor not in ANCHOR_MODES:
        raise PipelineError(f"{record['id']}: an explicit image anchor mode is required")
    if anchor == "reference":
        images = list(record["references"])
        if not spec["named_frames"]:
            # v2.0 has no reference mode; the anchors become the boundaries of a
            # keyframes transition, which pins both ends instead of guiding them.
            if len(images) == 1:
                return args + ["--mode", "ti2vid", "--image", images[0]]
            if len(images) == 2:
                return args + ["--mode", "keyframes", "--extra-body",
                               json.dumps({"image": images}, ensure_ascii=False)]
            raise PipelineError(
                f"{record['id']}: {spec['label']} crosses between two boundary images, "
                f"but {len(images)} references were resolved"
            )
        for url in images:
            args += ["--reference-image", url]
        return args + ["--mode", "reference"]
    if not first and not last:
        raise PipelineError(f"{record['id']}: anchor_mode {anchor!r} resolved to no media")
    if spec["named_frames"]:
        args += ["--mode", "keyframe"]
        if first:
            args += ["--first-frame", first]
        if last:
            args += ["--last-frame", last]
        return args
    if not first:
        raise PipelineError(
            f"{record['id']}: {spec['label']} cannot anchor on the last frame alone; supply "
            "first_frame as well, or pin the seam to the 2.5 Flash model"
        )
    if last:
        return args + ["--mode", "keyframes", "--extra-body",
                       json.dumps({"image": [first, last]}, ensure_ascii=False)]
    return args + ["--mode", "ti2vid", "--image", first]


def load_state(root: Path) -> dict:
    path = root / STATE_RELATIVE
    if not path.is_file():
        return {"clips": {}}
    try:
        state = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {"clips": {}}
    if not isinstance(state, dict) or not isinstance(state.get("clips"), dict):
        return {"clips": {}}
    return state


def save_state(root: Path, state: dict) -> None:
    path = root / STATE_RELATIVE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(state, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def record_anchor(root: Path, clip_id: str, url: str, mode: str, model: str | None = None) -> None:
    state = load_state(root)
    state["clips"][clip_id] = {
        "anchor_mode": mode,
        "anchor_model": model or (IMAGE_MODEL if mode == "generate" else None),
        "anchor_url": url,
        # A provider URL is pre-signed; the age decides whether it can still be
        # handed to a later connector run.
        "saved_at": datetime.datetime.now().isoformat(timespec="seconds"),
    }
    state["updated"] = datetime.datetime.now().isoformat(timespec="seconds")
    save_state(root, state)


def anchor_age_hours(entry: dict) -> float | None:
    stamp = str(entry.get("saved_at") or "")
    if not stamp:
        return None
    try:
        saved = datetime.datetime.fromisoformat(stamp)
    except ValueError:
        return None
    return (datetime.datetime.now() - saved).total_seconds() / 3600


def clear_anchor(root: Path, clip_id: str) -> None:
    state = load_state(root)
    if clip_id not in state["clips"]:
        return
    del state["clips"][clip_id]
    state["updated"] = datetime.datetime.now().isoformat(timespec="seconds")
    save_state(root, state)


def load_project_env(root: Path) -> None:
    """Read scoped provider settings; process values win and no shell is executed."""
    path = root / ".env"
    if not path.is_file():
        return
    try:
        path.resolve().relative_to(root.resolve())
    except ValueError as exc:
        raise PipelineError("project .env must stay inside the project") from exc
    try:
        from dotenv import dotenv_values
    except ImportError as exc:
        raise PipelineError("reading project .env requires python-dotenv from sn-image-base/requirements.txt") from exc
    allowed = {
        "AGNES_API_KEY", "AGNES_BASE_URL", "AGNES_SKILL_DIR", "SN_IMAGE_BASE_DIR",
        "SENSENOVA_API_KEY", "SN_ENV_FILE", "SN_BASE_URL", "SN_IMAGE_GEN_API_KEY",
        "SN_IMAGE_GEN_BASE_URL", "SN_IMAGE_GEN_MODEL_TYPE", "SN_IMAGE_GEN_MODEL",
        "SN_IMAGE_GEN_FALLBACK_MODEL",
    }
    for key, value in dotenv_values(path, interpolate=False, encoding="utf-8-sig").items():
        if key in allowed and value:
            os.environ.setdefault(key, value)


def image_cli(explicit: str | None) -> Path:
    """Resolve the SenseNova image runner: every anchor image comes from there."""
    if explicit:
        path = Path(explicit).expanduser().resolve()
        if not path.is_file():
            raise PipelineError(f"--image-cli does not exist: {path}")
        return path
    base = os.environ.get("SN_IMAGE_BASE_DIR", "").strip()
    if base:
        path = (Path(base).expanduser() / "scripts" / "sn_agent_runner.py").resolve()
        if not path.is_file():
            raise PipelineError(f"SN_IMAGE_BASE_DIR has no scripts/sn_agent_runner.py: {path}")
        return path
    sibling = Path(__file__).resolve().parents[2] / "sn-image-base" / "scripts" / "sn_agent_runner.py"
    if sibling.is_file():
        return sibling
    raise PipelineError(
        "cannot find the SenseNova image runner: pass --image-cli, or set SN_IMAGE_BASE_DIR to the "
        "directory containing the sn-image-base SKILL.md"
    )


